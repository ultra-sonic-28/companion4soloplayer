"""Generic attribute generation step (random, manual, mixed or auto)."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from functools import partial
from typing import Any, cast

from companion4soloplayer.core.creation.context import CharacterCreationContext, parse_path
from companion4soloplayer.core.creation.inputs import (
    InputField,
    InputKind,
    InputProvider,
    MissingInputError,
)
from companion4soloplayer.core.creation.steps.base import (
    CreationStep,
    StepConfigurationError,
)
from companion4soloplayer.core.creation.strategies import AttributeGenerationStrategy
from companion4soloplayer.core.dice_roller import DiceRoller

#: Generation modes understood by the step.
MODES: tuple[str, ...] = ("random", "manual", "mixed", "auto")

#: Per-block declaration of a step parameter: block id -> parameter value.
BlockParameters = Mapping[str, Any]


def _block_parameter(
    value: Any,
    block: str,
    *,
    step_id: str,
    name: str,
) -> Any:
    """Resolve one step parameter declared globally or per attribute block.

    ``mode``, ``strategy`` and the bounds accept either a plain value
    (every block of the step shares it) or a mapping keyed by the
    attribute block id (``{"attributes": "classic_4d6", "save":
    "class_saves"}``), which is how one workflow declares a different
    strategy per **type** of block.

    Args:
        value: Parameter value, either shared or keyed by block id.
            The ``"*"`` key applies to any block left undeclared.
        block: Block bound to this step (may be empty for the legacy
            ``system["attributes"]`` mode).
        step_id: Identifier of the step, used in error messages.
        name: Name of the parameter, used in error messages.

    Returns:
        The value declared for the block of this step, or ``value``
        itself when it is not a per-block mapping.

    Raises:
        StepConfigurationError: If a per-block value is used by a step
            bound to no block, or if the block declares no entry.
    """
    if not isinstance(value, Mapping):
        return value
    available = ", ".join(sorted(str(key) for key in value)) or "none"
    if not block:
        raise StepConfigurationError(
            f"Step {step_id!r}: parameter {name!r} is declared per block "
            "but the step binds no attribute block"
        )
    if block in value:
        return value[block]
    if "*" in value:
        return value["*"]
    raise StepConfigurationError(
        f"Step {step_id!r}: parameter {name!r} declares no value for block "
        f"{block!r} (available: {available})"
    )


class AttributeGenerationStep(CreationStep):
    """Generate the base values of the character attributes.

    Four generation modes cover requirement "random draw **or** manual
    assignment (for all or part of the attributes) **or** values
    assigned by the game system":

    - ``random``: every attribute is generated by the configured
      :class:`~companion4soloplayer.core.creation.strategies.AttributeGenerationStrategy`
      (resolved by name from ``context.system["strategies"]`` when a
      string is given), unless the provider already holds an answer for
      it (a die rolled in the Player dialog, a scripted fixture...);
    - ``manual``: every attribute is asked to the player
      (answer key ``<step_id>.<attribute>``);
    - ``mixed``: the attributes listed in ``manual_attributes`` are
      asked, the others are generated;
    - ``auto``: the strategy *assigns* the values, nothing is rolled
      and nothing is asked of the player: the step describes read-only
      fields (``InputKind.READONLY``) showing the effective value, and
      the bounds are not enforced (the values come from the game data,
      not from the player).

    ``mode``, ``strategy``, ``manual_attributes``, ``min_value`` and
    ``max_value`` may also be declared **per attribute block**, as a
    mapping keyed by block id (``"*"`` matching any other block), so a
    single workflow entry expanding over every block
    (``block: "*"``) can give each *type* of block its own strategy::

        mode: {attributes: random, save: auto}
        strategy: {attributes: classic_4d6, save: class_saves}

    The values are written as *base* values under ``target``; the
    bonuses and maluses granted by the rules are layered on top by the
    rules engine and read back with
    :meth:`CharacterCreationContext.effective`.

    Args:
        step_id: Unique identifier of the step.
        target: State path prefix storing the values (default
            ``values.attributes``).
        attributes: Explicit attribute names; when omitted the names
            are read from ``context.system["attributes"]`` (mapping
            keys, or list of names/declarations with ``id``, ``name``
            and ``description``).
        block: Identifier of the attribute block rendered by this step
            (key of ``context.system["attribute_blocks"]``); the block
            also provides the title of the dialog group. When empty the
            step reads ``context.system["attributes"]`` (with the title
            of ``context.system["attributes_title"]``).
        mode: ``random``, ``manual``, ``mixed`` or ``auto``, shared by
            every block or declared per block.
        strategy: Strategy instance, strategy name (key of
            ``context.system["strategies"]``) or strategy class, shared
            by every block or declared per block.
        manual_attributes: Attributes asked to the player in ``mixed``
            mode (shared or declared per block).
        min_value: Inclusive lower bound for manual answers and
            validation (shared or declared per block).
        max_value: Inclusive upper bound for manual answers and
            validation (shared or declared per block).
        roller: Optional dice roller (a fresh one is created per run).
        label: Human-readable label.

    Raises:
        StepConfigurationError: If ``step_id`` is empty, ``target`` is
            not a valid path, a per-block parameter cannot be resolved
            for the block of the step, the mode is unknown or the
            bounds are inconsistent.

    Example:
        >>> from companion4soloplayer.core.creation.inputs import (
        ...     MappingInputProvider)
        >>> from companion4soloplayer.core.creation.strategies import (
        ...     ConstantStrategy)
        >>> step = AttributeGenerationStep(strategy=ConstantStrategy(12))
        >>> context = CharacterCreationContext(
        ...     system={"attributes": ["strength", "charm"]})
        >>> step.execute(context, MappingInputProvider({}))
        >>> context.get("values.attributes.charm")
        12
    """

    def __init__(
        self,
        step_id: str = "attributes",
        *,
        target: str = "values.attributes",
        attributes: Sequence[str] | None = None,
        block: str = "",
        mode: str | BlockParameters = "random",
        strategy: AttributeGenerationStrategy | str | type | None | BlockParameters = None,
        manual_attributes: Sequence[str] | BlockParameters = (),
        min_value: int | None | BlockParameters = None,
        max_value: int | None | BlockParameters = None,
        roller: DiceRoller | None = None,
        label: str = "",
    ) -> None:
        """Initialize the step.

        Args:
            step_id: Unique identifier of the step.
            target: State path prefix storing the values.
            attributes: Explicit attribute names.
            block: Identifier of the attribute block declared in
                ``context.system["attribute_blocks"]``; empty reads
                ``context.system["attributes"]`` instead.
            mode: ``random``, ``manual``, ``mixed`` or ``auto``, either
                shared or keyed by block id.
            strategy: Strategy instance, name or class, either shared
                or keyed by block id.
            manual_attributes: Attributes asked in ``mixed`` mode,
                either shared or keyed by block id.
            min_value: Inclusive lower bound, either shared or keyed
                by block id.
            max_value: Inclusive upper bound, either shared or keyed
                by block id.
            roller: Optional dice roller.
            label: Human-readable label.

        Raises:
            StepConfigurationError: If the configuration is invalid.
        """
        super().__init__(step_id, label=label)
        parse_path(target)
        block_id = block.strip()
        # A parameter may be declared per block: the entry matching the
        # block bound to this step wins before anything is validated.
        resolved_mode: str = _block_parameter(mode, block_id, step_id=step_id, name="mode")
        resolved_strategy: AttributeGenerationStrategy | str | type | None = _block_parameter(
            strategy, block_id, step_id=step_id, name="strategy"
        )
        resolved_manual_attributes: Sequence[str] = _block_parameter(
            manual_attributes, block_id, step_id=step_id, name="manual_attributes"
        )
        resolved_min_value: int | None = _block_parameter(
            min_value, block_id, step_id=step_id, name="min_value"
        )
        resolved_max_value: int | None = _block_parameter(
            max_value, block_id, step_id=step_id, name="max_value"
        )
        if resolved_mode not in MODES:
            raise StepConfigurationError(
                f"Unknown attribute generation mode {resolved_mode!r} "
                f"(available: {', '.join(MODES)})"
            )
        if (
            resolved_min_value is not None
            and resolved_max_value is not None
            and resolved_min_value > resolved_max_value
        ):
            raise StepConfigurationError(
                f"min_value ({resolved_min_value}) cannot be greater than "
                f"max_value ({resolved_max_value})"
            )
        if attributes is not None:
            for position, attribute in enumerate(attributes):
                if not isinstance(attribute, str) or not attribute.strip():
                    raise StepConfigurationError(
                        f"Attribute #{position + 1} of step {step_id!r} must be a non-empty string"
                    )
        self._target = target
        self._attributes = tuple(attributes) if attributes is not None else None
        self._block = block_id
        self._mode = resolved_mode
        self._strategy = resolved_strategy
        self._manual_attributes = tuple(resolved_manual_attributes)
        self._min_value = resolved_min_value
        self._max_value = resolved_max_value
        self._roller = roller

    def attribute_entries(self, context: CharacterCreationContext) -> list[dict[str, str]]:
        """Return the attribute declarations of the game system.

        The declarations come from the first of these sources:

        1. the explicit ``attributes`` names given to the step;
        2. the attribute block named by the ``block`` parameter, read
           from ``context.system["attribute_blocks"]`` (the mapping of
           the blocks declared by the plugin ``attributes.yaml``, each
           block holding its ``title`` and its ``list``);
        3. ``context.system["attributes"]``, which accepts several
           shapes, so a game system can publish plain names or full
           declarations (a technical identifier, a display name and a
           description, as read from a plugin ``attributes.yaml``):

           - a mapping: its keys are the attribute identifiers;
           - a sequence of non-empty strings: each string is the
             identifier *and* the display name of one attribute;
           - a sequence of mappings: each entry declares a non-empty
             ``id`` (state path and answer key), an optional ``name``
             (text displayed in the dialog, falling back on the id) and
             an optional ``description`` (help text).

        Args:
            context: Current creation state.

        Returns:
            One ``{"id": ..., "name": ..., "description": ...}`` mapping
            per attribute, in declaration order; empty when the game
            system declares no attribute.

        Raises:
            StepConfigurationError: If
                ``context.system["attribute_blocks"]`` holds no block
                with the configured ``id``, or if the declarations are
                malformed (wrong type, entry without a valid
                ``id``/``name``, duplicate identifier).
        """
        if self._attributes is not None:
            return [
                {"id": attribute, "name": attribute, "description": ""}
                for attribute in self._attributes
            ]
        if self._block:
            raw = self._block_entries(context)
            source = f"system['attribute_blocks'][{self._block!r}]"
        else:
            raw = context.system.get("attributes")
            source = "system['attributes']"
        if raw is None:
            return []
        if isinstance(raw, Mapping):
            items: Sequence[Any] = list(raw.keys())
        elif isinstance(raw, Sequence) and not isinstance(raw, (str, bytes)):
            items = raw
        else:
            raise StepConfigurationError(
                f"{source} must be a list of names or a mapping, got {type(raw).__name__}"
            )
        entries: list[dict[str, str]] = []
        for position, item in enumerate(items):
            if isinstance(item, Mapping):
                entries.append(self._read_attribute_entry(item, position, source))
            elif isinstance(item, str) and item.strip():
                entries.append({"id": item.strip(), "name": item.strip(), "description": ""})
            else:
                raise StepConfigurationError(
                    f"Attribute #{position + 1} of {source} must be a "
                    "non-empty string or a mapping declaring a non-empty 'id'"
                )
        identifiers = [entry["id"] for entry in entries]
        duplicated = sorted({name for name in identifiers if identifiers.count(name) > 1})
        if duplicated:
            raise StepConfigurationError(
                f"{source} declares duplicate attribute id(s): {', '.join(duplicated)}"
            )
        return entries

    def _block_entries(self, context: CharacterCreationContext) -> Any:
        """Return the ``list`` of the attribute block rendered by this step.

        Args:
            context: Current creation state (provides the
                ``attribute_blocks`` mapping declared by the plugin).

        Returns:
            The raw attribute declarations of the configured block.

        Raises:
            StepConfigurationError: If the system declares no
                ``attribute_blocks`` mapping, no block with the
                configured identifier, or a block that is not a
                mapping.
        """
        blocks = context.system.get("attribute_blocks")
        if not isinstance(blocks, Mapping):
            raise StepConfigurationError(
                f"Step {self.step_id!r} renders the attribute block {self._block!r} but the "
                "game system declares no 'attribute_blocks' mapping"
            )
        block = blocks.get(self._block)
        if not isinstance(block, Mapping):
            available = ", ".join(sorted(blocks)) or "none"
            raise StepConfigurationError(
                f"Step {self.step_id!r}: unknown attribute block {self._block!r} "
                f"(available: {available})"
            )
        return block.get("list")

    @staticmethod
    def _read_attribute_entry(
        entry: Mapping[str, Any],
        position: int,
        source: str = "system['attributes']",
    ) -> dict[str, str]:
        """Read one attribute declaration mapping.

        Args:
            entry: Declared attribute (``id``, optional ``name`` and
                ``description``).
            position: Zero-based index of the entry, used in error
                messages.
            source: Declaration source (state path of the read
                declarations), used in error messages.

        Returns:
            The normalized ``{"id", "name", "description"}`` mapping.

        Raises:
            StepConfigurationError: If the identifier is missing or is
                not a non-empty string, or if the name/description are
                not strings.
        """
        identifier = entry.get("id")
        if not isinstance(identifier, str) or not identifier.strip():
            raise StepConfigurationError(
                f"Attribute #{position + 1} of {source} must define a non-empty 'id'"
            )
        name = entry.get("name", identifier)
        if not isinstance(name, str) or not name.strip():
            raise StepConfigurationError(
                f"Attribute {identifier.strip()!r} must define a non-empty 'name' string"
            )
        description = entry.get("description", "")
        if not isinstance(description, str):
            raise StepConfigurationError(
                f"Attribute {identifier.strip()!r} must define a 'description' string"
            )
        return {"id": identifier.strip(), "name": name.strip(), "description": description}

    def attribute_names(self, context: CharacterCreationContext) -> list[str]:
        """Return the attribute identifiers of the game system.

        Args:
            context: Current creation state.

        Returns:
            The explicit attribute names, else the identifiers declared
            in ``context.system["attributes"]`` (list of names or
            entries, or mapping keys); an empty list when the system
            declares none.

        Raises:
            StepConfigurationError: If ``context.system["attributes"]``
                is malformed.
        """
        return [entry["id"] for entry in self.attribute_entries(context)]

    def attribute_labels(self, context: CharacterCreationContext) -> dict[str, str]:
        """Return the display name of each attribute of the system.

        Args:
            context: Current creation state.

        Returns:
            Display name of each attribute, keyed by identifier; a
            system declaring plain names yields name == identifier.

        Raises:
            StepConfigurationError: If ``context.system["attributes"]``
                is malformed.
        """
        return {entry["id"]: entry["name"] for entry in self.attribute_entries(context)}

    def attribute_descriptions(self, context: CharacterCreationContext) -> dict[str, str]:
        """Return the description of each attribute of the system.

        Args:
            context: Current creation state.

        Returns:
            Description of each attribute, keyed by identifier (empty
            string when the declaration carries none).

        Raises:
            StepConfigurationError: If ``context.system["attributes"]``
                is malformed.
        """
        return {entry["id"]: entry["description"] for entry in self.attribute_entries(context)}

    def display_label(self, context: CharacterCreationContext) -> str:
        """Return the title of the attributes block.

        The title comes from the declaration driving this step: the
        ``title`` of the attribute block named by the ``block``
        parameter (declared by the plugin, typically read from its
        ``attributes.yaml`` document), else
        ``context.system["attributes_title"]``. Both fall back on the
        step label when the game system declares no title.

        Args:
            context: Current creation state.

        Returns:
            The block title displayed by the UI.

        Raises:
            StepConfigurationError: If the configured block is unknown
                (see :meth:`attribute_entries`).
        """
        title: Any = None
        if self._block:
            blocks = context.system.get("attribute_blocks")
            if isinstance(blocks, Mapping) and isinstance(blocks.get(self._block), Mapping):
                title = cast(Mapping[str, Any], blocks[self._block]).get("title")
            else:
                # Unknown block: let attribute_entries raise the same
                # explicit configuration error.
                self.attribute_entries(context)
        else:
            title = context.system.get("attributes_title")
        if isinstance(title, str) and title.strip():
            return title.strip()
        return self.label

    def roll_attribute(
        self,
        attribute: str,
        context: CharacterCreationContext,
        roller: DiceRoller | None = None,
    ) -> int:
        """Generate one attribute value with the configured strategy.

        This is the public entry point used both by :meth:`execute`
        when the provider holds no answer (always in ``auto`` mode),
        and by the die button of the Player dialog. The current state
        is forwarded to the strategy, so a strategy may adapt to the
        choices made so far (see
        :meth:`~companion4soloplayer.core.creation.strategies.AttributeGenerationStrategy.roll_for`).

        Args:
            attribute: Attribute name to generate.
            context: Current creation state (resolves the named
                strategies of ``context.system["strategies"]`` and is
                forwarded to the strategy).
            roller: Optional dice roller (a fresh one is created when
                omitted).

        Returns:
            The generated base value.

        Raises:
            StepConfigurationError: If no strategy is configured, the
                name is unknown or the configured value is not an
                attribute strategy.
        """
        strategy = self._resolve_strategy(context)
        roller = roller or DiceRoller()
        # The context-aware entry point lets a strategy adapt to the
        # state chosen so far; the base implementation delegates to
        # the plain ``roll`` contract.
        return strategy.roll_for(attribute, roller, context)

    def describe_inputs(self, context: CharacterCreationContext) -> tuple[InputField, ...]:
        """Describe one field per attribute of the game system.

        A randomly generated attribute is a ``DICE`` field: the UI
        shows a label and a die button, and the rolled value becomes
        the answer kept by the step. A manually entered attribute is a
        ``NUMBER`` field (plain text entry). An attribute generated in
        ``auto`` mode is a ``READONLY`` field: the step assigns the
        value itself, so nothing is asked of the player and the field
        displays the effective value (base value plus rule operations)
        recomputed at every refresh.

        The label of each field is the display ``name`` declared by
        the game system (falling back on the attribute identifier) and
        the field description is the help text of the declaration, so a
        plugin ``attributes.yaml`` fully drives what the dialog shows.

        Args:
            context: Current creation state (provides the attribute
                declarations).

        Returns:
            One field per attribute, in declaration order; empty when
            the game system declares no attribute.

        Raises:
            StepConfigurationError: If ``context.system["attributes"]``
                is malformed.
        """
        labels = self.attribute_labels(context)
        descriptions = self.attribute_descriptions(context)
        fields: list[InputField] = []
        for attribute in self.attribute_names(context):
            key = f"{self.step_id}.{attribute}"
            label = labels.get(attribute, attribute)
            description = descriptions.get(attribute, "")
            if self._mode == "auto":
                # No draw, no answer: display the value computed by
                # the strategy and layered with the rule bonuses.
                fields.append(
                    InputField(
                        key=key,
                        label=label,
                        kind=InputKind.READONLY,
                        description=description,
                        value=context.effective(f"{self._target}.{attribute}"),
                    )
                )
                continue
            manual = self._is_manual(attribute)
            roll = None if manual else partial(self.roll_attribute, attribute, context)
            fields.append(
                InputField(
                    key=key,
                    label=label,
                    kind=InputKind.NUMBER if manual else InputKind.DICE,
                    min_value=self._min_value,
                    max_value=self._max_value,
                    roll=roll,
                    description=description,
                )
            )
        return tuple(fields)

    def is_applicable(self, context: CharacterCreationContext) -> bool:
        """Tell whether the step must run.

        Args:
            context: Current creation state.

        Returns:
            True when the game system declares at least one attribute.

        Raises:
            StepConfigurationError: If the system attribute declaration
                is malformed.
        """
        return bool(self.attribute_names(context))

    def execute(self, context: CharacterCreationContext, inputs: InputProvider) -> None:
        """Generate, assign or ask every attribute value.

        In ``auto`` mode nothing is asked of the player: the value
        always comes from the configured strategy.

        Args:
            context: Current creation state, updated in place under
                ``target``.
            inputs: Answer source of the session.

        Raises:
            InputError: If an answer is out of bounds, or missing for a
                manual attribute.
            StepConfigurationError: If the system data or the strategy
                configuration is invalid.
        """
        names = self.attribute_names(context)
        if not names:
            return
        roller = self._roller or DiceRoller()
        for attribute in names:
            key = f"{self.step_id}.{attribute}"
            if self._mode == "auto":
                # Assigned value: the player is never asked for it.
                value = self.roll_attribute(attribute, context, roller)
                context.set(f"{self._target}.{attribute}", value)
                continue
            try:
                # A recorded answer (a die rolled by the Player dialog,
                # a scripted fixture...) wins over the strategy, which
                # stays the fallback producing the random value.
                value = inputs.ask_number(
                    key,
                    f"{attribute}",
                    minimum=self._min_value,
                    maximum=self._max_value,
                )
            except MissingInputError:
                if self._is_manual(attribute):
                    raise
                value = self.roll_attribute(attribute, context, roller)
            context.set(f"{self._target}.{attribute}", value)

    def validate(self, context: CharacterCreationContext) -> list[str]:
        """Validate the generated attribute values.

        In ``auto`` mode the configured bounds are not enforced: the
        values are assigned from the game data (a saving throw of 19,
        for instance) and never come from the player.

        Args:
            context: Current creation state.

        Returns:
            Error messages; empty when every attribute holds a valid
            integer within the configured bounds.
        """
        errors: list[str] = []
        try:
            names = self.attribute_names(context)
        except StepConfigurationError as exc:
            return [str(exc)]
        known = set(names)
        for attribute in self._manual_attributes:
            if attribute not in known:
                errors.append(f"Manual attribute {attribute!r} is not declared by the system")
        bounded = self._mode != "auto"
        for attribute in names:
            path = f"{self._target}.{attribute}"
            if not context.has(path):
                errors.append(f"Missing value for attribute {attribute!r} ({path})")
                continue
            value = context.get(path)
            if not isinstance(value, int) or isinstance(value, bool):
                errors.append(
                    f"Attribute {attribute!r} must be an integer, got {type(value).__name__}"
                )
                continue
            if not bounded:
                continue
            if self._min_value is not None and value < self._min_value:
                errors.append(f"Attribute {attribute!r} must be >= {self._min_value}, got {value}")
            if self._max_value is not None and value > self._max_value:
                errors.append(f"Attribute {attribute!r} must be <= {self._max_value}, got {value}")
        return errors

    def _is_manual(self, attribute: str) -> bool:
        """Tell whether ``attribute`` is asked to the player.

        Args:
            attribute: Attribute name.

        Returns:
            True in ``manual`` mode, or in ``mixed`` mode when the
            attribute is listed in ``manual_attributes``.
        """
        if self._mode == "manual":
            return True
        if self._mode == "mixed":
            return attribute in self._manual_attributes
        return False

    def _resolve_strategy(self, context: CharacterCreationContext) -> AttributeGenerationStrategy:
        """Resolve the configured generation strategy.

        Args:
            context: Current creation state (provides the named
                strategies of ``context.system["strategies"]``).

        Returns:
            The strategy to use for the randomly generated attributes.

        Raises:
            StepConfigurationError: If no strategy is configured, the
                name is unknown, or the configured value is neither a
                strategy nor an instantiable class.
        """
        strategy: AttributeGenerationStrategy | str | type | None = self._strategy
        if strategy is None:
            raise StepConfigurationError(
                f"Step {self.step_id!r}: no attribute generation strategy configured"
            )
        if isinstance(strategy, str):
            registry = context.system.get("strategies", {})
            if not isinstance(registry, Mapping) or strategy not in registry:
                available = sorted(registry) if isinstance(registry, Mapping) else []
                raise StepConfigurationError(
                    f"Step {self.step_id!r}: unknown strategy {strategy!r} "
                    f"(available: {', '.join(available) or 'none'})"
                )
            strategy = registry[strategy]
        if isinstance(strategy, type):
            strategy_class = strategy
            try:
                strategy = strategy_class()
            except Exception as exc:
                raise StepConfigurationError(
                    f"Step {self.step_id!r}: cannot instantiate strategy "
                    f"{strategy_class.__name__}: {exc}"
                ) from exc
        if not callable(getattr(strategy, "roll", None)):
            raise StepConfigurationError(
                f"Step {self.step_id!r}: {strategy!r} is not an attribute strategy"
            )
        # The branches above exhaustively handled None, str and type, and
        # the roll attribute was just checked: the cast states that
        # guarantee without relying on the checker's narrowing.
        return cast(AttributeGenerationStrategy, strategy)
